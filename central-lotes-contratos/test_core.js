const assert=require('node:assert/strict');
const c=require('./core.js');
const form={inicio:1,fim:250,origem:'EXTERNO',destino:'INTERNO',responsavel:'Operação',limite:250};
const l=c.normalizarLote(form,[]);
assert.equal(l.fim-l.inicio+1,250);
assert.match(l.chave,/contratos-v1/);
assert.throws(()=>c.normalizarLote({...form,inicio:200,fim:300},[l]),/Sobreposição/);
assert.throws(()=>c.normalizarLote({...form,inicio:1,fim:300},[]),/excede limite/);
assert.throws(()=>c.normalizarLote({...form,inicio:0,fim:3},[]),/inválido/);
assert.throws(()=>c.normalizarLote({...form,inicio:2,fim:1},[]),/inválido/);
assert.throws(()=>c.atualizarQuantidades(l,{sucesso:249,falha:2,tentativas:0}),/excedem/);
assert.throws(()=>c.atualizarQuantidades(l,{sucesso:-1,falha:2,tentativas:0}),/inteiros/);
assert.equal(c.atualizarQuantidades(l,{sucesso:200,falha:40,tentativas:1}).informadosSucesso,200);
assert.throws(()=>c.validarRegistro({tipo:'ACAO_EFETIVA_INFORMADA',etapa:5,descricao:'Publicação final realizada',responsavel:'Pessoa',checkpoint:'cp'}, {...l,etapa:4}),/não podem ser declarados/);
assert.throws(()=>c.validarRegistro({tipo:'FATO_INFORMADO',etapa:3,descricao:'Registro de conformidade',responsavel:'Pessoa',checkpoint:'cp'}, l),/saltar/);
assert.throws(()=>c.validarRegistro({tipo:'FATO_INFORMADO',etapa:1,descricao:'Registro de conformidade',responsavel:'Pessoa'}, l),/checkpoint/);
assert.throws(()=>c.validarRegistro({tipo:'FATO_INFORMADO',etapa:0,descricao:'Registro de conformidade',responsavel:'Pessoa',sha:'123'}, l),/SHA-256/);
assert.equal(c.validarRegistro({tipo:'FATO_INFORMADO',etapa:0,descricao:'Registro de conferência documental',responsavel:'Pessoa'},l).prova,'DECLARACAO_LOCAL_NAO_VERIFICADA');
assert.equal(c.estatisticas([l],110000).validadoExternamente,0);
assert.equal(c.estatisticas([l],110000).cadastrados,250);
assert.throws(()=>c.validarConfig({limite:2000,paralelismo:2,retry:3,backoff:2,teto:60}),/limites/);
assert.equal(c.validarConfig({limite:200,paralelismo:2,retry:3,backoff:2,teto:60}).publicacao,'BLOQUEADA');
const r=c.conciliar(l,{origem:200,baixados:190,conferidos:185,internos:185,publicados:180,shaManifesto:'a'.repeat(64)});
assert.equal(r.status,'DIVERGENCIA_INFORMADA');
assert.ok(r.divergencias.length>0);
const sem=c.conciliar(l,{origem:200,baixados:200,conferidos:200,internos:200,publicados:200,shaManifesto:'a'.repeat(64)});
assert.equal(sem.status,'CONTAGENS_IGUAIS_INFORMADAS');
assert.equal(sem.prova,'DECLARACAO_LOCAL_NAO_VERIFICADA');
assert.throws(()=>c.conciliar(l,{origem:200,baixados:190,conferidos:190,internos:190,publicados:190}),/SHA-256/);
assert.throws(()=>c.conciliar(l,{origem:1000,baixados:0,conferidos:0,internos:0,publicados:0}),/inválidas/);
console.log('PASS 23 verificações de regras de negócio (inclui reconciliação positiva/negativa).');
